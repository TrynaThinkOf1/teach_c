/*
 * A keyword in C (or any other language) is a reserved word that you use to tell the
 * compiler to do something, or to do something in a certain way
 *
 * below is a list of all of the C keywords, don't focus on memorizing the list, most
 * code editors will highlight keywords, and as you become more experienced you will
 * inadvertantly memorize the list by virtue of use. Only a few of the words will have
 * explanations below because I don't want you to dwell on them for now, only once we
 * get to whichever lesson first uses a keyword to do something.
 */

